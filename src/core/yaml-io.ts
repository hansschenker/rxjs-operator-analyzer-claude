import { isMap, isScalar, parse, parseDocument, Scalar, visit, type YAMLMap, type YAMLSeq } from 'yaml';
import { parseOperatorSpec, safeParseOperatorSpec, type SafeParseResult } from './schema';
import type { OperatorSpec, SimulationResult, TraceStep } from './types';

export const GENERATED_MARKER = ' generated by `rxjs-operator-analyzer analyze` — do not edit by hand';

export function parseOperatorYaml(text: string): OperatorSpec {
  return parseOperatorSpec(parse(text));
}

export function safeParseOperatorYaml(text: string): SafeParseResult {
  let data: unknown;
  try {
    data = parse(text);
  } catch (e) {
    return {
      ok: false,
      issues: [{ severity: 'error', code: 'yaml', message: (e as Error).message }],
    };
  }
  return safeParseOperatorSpec(data);
}

function stepToPlain(step: TraceStep): Record<string, unknown> {
  const outputs = step.outputs.map((o) => ({
    kind: o.kind,
    ...(o.label !== undefined ? { label: o.label } : {}),
    ...(o.window !== undefined ? { window: o.window } : {}),
  }));
  return {
    frame: step.frame,
    kind: step.kind,
    input: step.input,
    rule: step.rule,
    state: step.state,
    outputs,
    ...(step.data !== undefined ? { data: step.data } : {}),
  };
}

function setKeyComment(map: YAMLMap, key: string, comment: string): void {
  const pair = map.items.find((p) => (isScalar(p.key) ? p.key.value : p.key) === key);
  if (!pair) return;
  if (!isScalar(pair.key)) pair.key = new Scalar(key);
  (pair.key as Scalar).commentBefore = comment;
}

const PROSE_WIDTH = 100;

function wrapProse(value: string, width: number): string {
  const paragraphs = value.replace(/\r\n/g, '\n').split(/\n{2,}/);
  return paragraphs
    .map((paragraph) => {
      const words = paragraph.replace(/\s*\n\s*/g, ' ').trim().split(/\s+/);
      const lines: string[] = [];
      let line = '';
      for (const word of words) {
        if (line !== '' && line.length + 1 + word.length > width) {
          lines.push(line);
          line = word;
        } else {
          line = line === '' ? word : `${line} ${word}`;
        }
      }
      if (line !== '') lines.push(line);
      return lines.join('\n');
    })
    .join('\n\n');
}

/**
 * Trace steps are emitted as one flow mapping per line, which needs line folding disabled. Folded
 * (`>`) prose blocks would then come out as one very long line, so they are re-wrapped into literal
 * (`|`) blocks that keep their line breaks.
 */
function keepProseWrapped(doc: ReturnType<typeof parseDocument>): void {
  visit(doc, {
    Scalar(_key, node) {
      if (node.type === 'BLOCK_FOLDED' && typeof node.value === 'string') {
        node.type = 'BLOCK_LITERAL';
        node.value = `${wrapProse(node.value, PROSE_WIDTH)}\n`;
      }
    },
  });
}

/**
 * Write generated scenario results (`expected`, `expectedValues`, `trace`) back into the YAML text,
 * preserving every hand-written key and comment through the `yaml` Document API.
 */
export function updateScenarioResults(text: string, results: readonly SimulationResult[]): string {
  const doc = parseDocument(text);
  keepProseWrapped(doc);
  const scenarios = doc.get('scenarios');
  if (!scenarios || typeof scenarios !== 'object' || !('items' in scenarios)) {
    throw new Error('operator YAML has no `scenarios` sequence');
  }
  for (const item of (scenarios as YAMLSeq).items) {
    if (!isMap(item)) continue;
    const name = item.get('name');
    const result = results.find((r) => r.scenario === name);
    if (!result) continue;

    item.set('expected', result.expected);
    const values = doc.createNode(result.expectedValues) as YAMLMap;
    values.flow = true;
    item.set('expectedValues', values);
    const trace = doc.createNode(result.steps.map(stepToPlain)) as YAMLSeq;
    for (const node of trace.items) if (isMap(node)) node.flow = true;
    item.set('trace', trace);
    setKeyComment(item, 'expected', GENERATED_MARKER);
  }
  return doc.toString({ lineWidth: 0 });
}
