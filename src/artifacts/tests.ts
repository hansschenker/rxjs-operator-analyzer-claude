import { marbleLetters } from '../core/marble';
import { downstreamLog } from '../core/simulator';
import type { OperatorSpec, ScenarioSpec, SimulationResult } from '../core/types';

export type TestRunner = 'jest' | 'vitest';

export interface TestGenOptions {
  readonly runner?: TestRunner;
  readonly higherOrder: boolean;
  /** Path of the YAML the file was generated from (for the header comment). */
  readonly sourceFile?: string;
}

function js(value: unknown): string {
  return JSON.stringify(value);
}

function operatorCall(spec: OperatorSpec, scenario: ScenarioSpec): string {
  const args = spec.parameters
    .map((p) => scenario.params[p.name])
    .map((v) => (v === undefined ? undefined : js(v)));
  while (args.length > 0 && args[args.length - 1] === undefined) args.pop();
  return `${spec.operator}(${args.map((a) => a ?? 'undefined').join(', ')})`;
}

function valuesLiteral(scenario: ScenarioSpec): string {
  const letters = marbleLetters(scenario.source);
  const entries = letters.map((l) => `${js(l)}: ${js(scenario.values?.[l] ?? l)}`);
  return `{ ${entries.join(', ')} }`;
}

/**
 * Artifact 5: automated test cases. Jest-compatible by default (globals `describe/it/expect`);
 * `runner: 'vitest'` adds the explicit import. Each scenario of the YAML becomes one test that
 * runs the REAL RxJS operator under TestScheduler and compares its observable history with the
 * Mealy model's trace, so the generated file doubles as a differential test of the analysis.
 */
export function renderTestFile(spec: OperatorSpec, results: readonly SimulationResult[], options: TestGenOptions): string {
  const runner = options.runner ?? 'jest';
  const out: string[] = [];
  out.push('/**');
  out.push(` * Generated by rxjs-operator-analyzer from ${options.sourceFile ?? `operators/${spec.operator}.yaml`} — do not edit.`);
  out.push(` * ${spec.operator} — Mealy 6-tuple State Transition Table test cases (${spec.source ? `${spec.source.package} ${spec.source.version}` : 'RxJS'}).`);
  out.push(' *');
  out.push(' * Each test replays one scenario through the real operator with TestScheduler (virtual time,');
  out.push(' * one frame per marble character) and asserts the exact notification history predicted by the');
  out.push(' * executable Mealy model. The rule ids in the comments reference the State Transition Table.');
  out.push(' */');
  if (runner === 'vitest') out.push("import { describe, expect, it } from 'vitest';");
  out.push(`import { ${options.higherOrder ? 'isObservable, ' : ''}${spec.operator}, type OperatorFunction } from 'rxjs';`);
  out.push("import { TestScheduler } from 'rxjs/testing';");
  out.push('');
  out.push('function fmt(value: unknown): string {');
  out.push("  if (typeof value === 'string') return value;");
  out.push('  if (Array.isArray(value)) return `[${value.map(fmt).join(\',\')}]`;');
  out.push('  return JSON.stringify(value) ?? String(value);');
  out.push('}');
  out.push('');
  out.push('/** Runs `source` through `operator` and returns `"<frame> <event>"` lines in delivery order. */');
  out.push('function history(source: string, values: Record<string, unknown>, operator: OperatorFunction<unknown, unknown>): string[] {');
  out.push('  const log: string[] = [];');
  out.push('  const scheduler = new TestScheduler((actual, expected) => expect(actual).toEqual(expected));');
  out.push('  scheduler.run(({ cold }) => {');
  out.push('    const now = (): number => scheduler.now();');
  out.push('    let windows = 0;');
  out.push('    cold(source, values).pipe(operator).subscribe({');
  out.push('      next: (value) => {');
  if (options.higherOrder) {
    out.push('        if (isObservable(value)) {');
    out.push('          const id = `w${++windows}`;');
    out.push('          log.push(`${now()} open(${id})`);');
    out.push('          value.subscribe({');
    out.push('            next: (v) => log.push(`${now()} ${id}.next(${fmt(v)})`),');
    out.push('            error: () => log.push(`${now()} ${id}.error`),');
    out.push('            complete: () => log.push(`${now()} ${id}.complete`),');
    out.push('          });');
    out.push('          return;');
    out.push('        }');
  } else {
    out.push('        void windows;');
  }
  out.push('        log.push(`${now()} next(${fmt(value)})`);');
  out.push('      },');
  out.push('      error: () => log.push(`${now()} error`),');
  out.push('      complete: () => log.push(`${now()} complete`),');
  out.push('    });');
  out.push('  });');
  out.push('  return log;');
  out.push('}');
  out.push('');
  out.push(`describe('${spec.operator} — Mealy state transition table', () => {`);
  for (const scenario of spec.scenarios) {
    const result = results.find((r) => r.scenario === scenario.name);
    if (!result) continue;
    const rules = result.steps.map((s) => s.rule).join(' ');
    const expected = downstreamLog(result.downstream);
    out.push(`  // ${scenario.title ?? scenario.name}`);
    out.push(`  // rules fired: ${rules}`);
    out.push(`  it(${js(`${scenario.name}: ${result.params} on ${scenario.source}`)}, () => {`);
    out.push(`    const actual = history(${js(scenario.source)}, ${valuesLiteral(scenario)}, ${operatorCall(spec, scenario)} as OperatorFunction<unknown, unknown>);`);
    if (expected.length === 0) {
      out.push('    expect(actual).toEqual([]);');
    } else {
      out.push('    expect(actual).toEqual([');
      const byFrame = new Map<number, string>();
      for (const s of result.steps) if (!byFrame.has(s.frame)) byFrame.set(s.frame, `${s.input} → ${s.rule}`);
      let lastFrame = -1;
      for (const line of expected) {
        const frame = Number(line.split(' ')[0]);
        const comment = frame !== lastFrame ? `  // frame ${frame}: ${byFrame.get(frame) ?? ''}` : '';
        lastFrame = frame;
        out.push(`      ${js(line)},${comment}`);
      }
      out.push('    ]);');
    }
    out.push('  });');
    out.push('');
  }
  // rule coverage summary
  const coverage = new Map<string, Set<string>>();
  for (const r of results) for (const s of r.steps) {
    const set = coverage.get(s.rule) ?? new Set<string>();
    set.add(r.scenario);
    coverage.set(s.rule, set);
  }
  out.push('  // Rule coverage of this file:');
  for (const rule of spec.mealy.transitions) {
    const scenarios = coverage.get(rule.id);
    out.push(`  //   ${rule.id.padEnd(4)} ${scenarios ? [...scenarios].join(', ') : rule.reachable === false ? '(unreachable by protocol)' : 'NOT COVERED'}`);
  }
  out.push('});');
  out.push('');
  return out.join('\n');
}
